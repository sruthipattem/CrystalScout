def make_ml_data(df, split_name):
    data = df.copy()

    # Exclude below-threshold values such as <1E-10.
    raw_y = data[TARGET].astype("string").str.strip()
    censored = raw_y.str.startswith("<", na=False)
    y = pd.to_numeric(raw_y.mask(censored), errors="coerce")

    valid = y.notna() & np.isfinite(y) & (y > 0)

    X = data.loc[valid, FEATURES].apply(
        pd.to_numeric, errors="coerce"
    )
    y = y.loc[valid]

    # Remove rows where every feature is missing.
    has_features = X.notna().any(axis=1)
    X = X.loc[has_features]
    y = y.loc[has_features]

    print(f"\n{split_name}")
    print("Original rows:", len(data))
    print("Below-threshold labels:", int(censored.sum()))
    print("Usable rows:", len(X))
    print("Rows with all features missing:",
          int((~data.loc[valid, FEATURES].notna().any(axis=1)).sum()))

    return X, np.log10(y.astype(float))

