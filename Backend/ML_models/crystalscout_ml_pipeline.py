import numpy as np
import pandas as pd
from tqdm.auto import tqdm

prediction_rows = []
failed_rows = []

batch_size = 250

for start in tqdm(range(0, len(screened_docs), batch_size)):
    batch_docs = screened_docs[start:start + batch_size]
    batch_features = []

    for doc in batch_docs:
        try:
            features = make_candidate_features(doc)
            batch_features.append(features)
        except Exception as e:
            failed_rows.append({
                "material_id": doc.material_id,
                "formula": doc.formula_pretty,
                "error": str(e)
            })

    if not batch_features:
        continue

    X_batch = pd.DataFrame(batch_features, columns=expected_features)

    # The saved pipeline includes median imputation.
    # Predict log10 conductivity, then convert to S/cm.
    log_predictions = model.predict(X_batch)
    conductivity_predictions = np.power(10.0, log_predictions)

    successful_docs = [
        doc for doc in batch_docs
        if not any(
            item["material_id"] == doc.material_id
            for item in failed_rows[-len(batch_docs):]
        )
    ]

    for doc, log_pred, sigma_pred in zip(
        successful_docs, log_predictions, conductivity_predictions
    ):
        prediction_rows.append({
            "material_id": doc.material_id,
            "formula": doc.formula_pretty,
            "predicted_log10_conductivity": float(log_pred),
            "predicted_conductivity_S_cm": float(sigma_pred),
            "band_gap_eV": doc.band_gap,
            "energy_above_hull_eV_atom": doc.energy_above_hull
        })

predictions_df = pd.DataFrame(prediction_rows)

print("Screened candidates:", len(screened_docs))
print("Successful predictions:", len(predictions_df))
print("Failed feature extractions:", len(failed_rows))

display(
    predictions_df.sort_values(
        "predicted_log10_conductivity",
        ascending=False
    ).head(20)
)

