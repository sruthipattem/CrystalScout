from pymatgen.core import Composition
from matminer.featurizers.composition import ElementProperty

TARGET = "Ionic conductivity (S cm-1)"
FORMULA = "True Composition"

STRUCTURE_FEATURES = [
    "Space group #", "a", "b", "c",
    "alpha", "beta", "gamma"
]

featurizer = ElementProperty.from_preset("magpie")
composition_feature_names = featurizer.feature_labels()

def build_composition_data(df, split_name):
    raw = df[TARGET].astype("string").str.strip()
    censored = raw.str.startswith("<", na=False)
    conductivity = pd.to_numeric(raw.mask(censored), errors="coerce")

    valid = (
        conductivity.notna()
        & np.isfinite(conductivity)
        & (conductivity > 0)
    )

    data = df.loc[valid].copy()
    conductivity = conductivity.loc[valid]

    feature_rows = []
    valid_indices = []

    for idx, formula in data[FORMULA].items():
        try:
            comp = Composition(str(formula))
            values = featurizer.featurize(comp)

            if np.isfinite(values).all():
                feature_rows.append(values)
                valid_indices.append(idx)
        except Exception:
            continue

    data = data.loc[valid_indices].copy()
    conductivity = conductivity.loc[valid_indices]

    comp_X = pd.DataFrame(
        feature_rows,
        index=valid_indices,
        columns=composition_feature_names
    )

    struct_X = data[STRUCTURE_FEATURES].apply(
        pd.to_numeric, errors="coerce"
    )

    X = pd.concat([comp_X, struct_X], axis=1)
    y = np.log10(conductivity.astype(float))

    print(f"\n{split_name}")
    print("Valid rows:", len(X))
    print("Composition features:", len(composition_feature_names))
    print("Total features:", X.shape[1])

    return X, y, data

