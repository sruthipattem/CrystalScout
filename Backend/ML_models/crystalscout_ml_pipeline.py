def make_candidate_features(doc):
    """Create the same 139 input features used during training."""
    comp = Composition(doc.formula_pretty)
    magpie_values = magpie.featurize(comp)

    features = dict(zip(magpie.feature_labels(), magpie_values))

    lattice = doc.structure.lattice
    features.update({
        "Space group #": (
            doc.symmetry.number if doc.symmetry else np.nan
        ),
        "a": lattice.a,
        "b": lattice.b,
        "c": lattice.c,
        "alpha": lattice.alpha,
        "beta": lattice.beta,
        "gamma": lattice.gamma
    })

    # Enforce the exact feature order expected by the model
    return pd.Series(features).reindex(expected_features)

