def clean_conductivity(df):
    result = df.copy()

    raw = result[TARGET].astype("string").str.strip()

    # Identify censored measurements such as <1E-10.
    censored = raw.str.startswith("<", na=False)

    # Convert ordinary numerical measurements.
    numeric = pd.to_numeric(
        raw.mask(censored),
        errors="coerce"
    )

    valid = (
        numeric.notna()
        & np.isfinite(numeric)
        & (numeric > 0)
        & ~censored
    )

    result[TARGET] = numeric

    cleaned = result.loc[valid].copy()

    return cleaned, {
        "original_rows": len(df),
        "below_threshold": int(censored.sum()),
        "invalid_or_missing": int((~censored & ~valid).sum()),
        "usable_rows": len(cleaned)
    }

